/// Tamaños fijos de componentes: íconos, alturas de botones y loaders.
class AppSizes {
  /// Ícono pequeño (dentro de botones y chips).
  static const double iconSm = 16;

  /// Ícono estándar.
  static const double iconMd = 24;

  /// Ícono grande.
  static const double iconLg = 32;

  /// Ícono de estados vacíos y de error.
  static const double iconXl = 48;

  /// Alto de un botón pequeño.
  static const double buttonHeightSm = 36;

  /// Alto de un botón mediano (por defecto).
  static const double buttonHeightMd = 44;

  /// Alto de un botón grande.
  static const double buttonHeightLg = 52;

  /// Diámetro de un loader pequeño.
  static const double loaderSm = 16;

  /// Diámetro de un loader mediano (por defecto).
  static const double loaderMd = 32;

  /// Diámetro de un loader grande.
  static const double loaderLg = 48;
}
