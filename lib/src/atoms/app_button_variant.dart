/// Variantes visuales de un `AppButton`.
enum AppButtonVariant {
  /// Acción principal de la pantalla (relleno de color).
  primary,

  /// Acción secundaria (relleno suave).
  secondary,

  /// Acción de menor énfasis (solo borde).
  outlined,

  /// Acción discreta (sin fondo ni borde).
  text,

  /// Acción destructiva (por ejemplo, eliminar).
  danger,
}
